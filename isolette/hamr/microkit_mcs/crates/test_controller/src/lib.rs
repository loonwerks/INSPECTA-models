use crate::bridge::test_controller_process_test_controller_thread_api::{self as api, *};
use crate::component::test_controller_process_test_controller_thread_app::*;
use data::*;

static mut app: Option<test_controller_process_test_controller_thread> = None;
static mut init_api: test_controller_process_test_controller_thread_Application_Api<test_controller_process_test_controller_thread_Initialization_Api> = api::init_api();
static mut compute_api: test_controller_process_test_controller_thread_Application_Api<test_controller_process_test_controller_thread_Compute_Api> = api::compute_api();

#[no_mangle]
pub extern "C" fn test_controller_process_test_controller_thread_initialize() {
  logging::init_logging();

  unsafe {
    #[cfg(test)]
    crate::bridge::extern_c_api::initialize_test_globals();

    let mut _app = test_controller_process_test_controller_thread::new();
    _app.initialize(&mut init_api);
    app = Some(_app);
  }
}

#[no_mangle]
pub extern "C" fn test_controller_process_test_controller_thread_timeTriggered() {
  unsafe {
    if let Some(_app) = app.as_mut() {
      _app.timeTriggered(&mut compute_api);
      // Run the system test suite.  The controller is dispatched once: by the
      // scheduler kick sent after every partition has reported ready.
      crate::system_tests::run_all();
    } else {
      panic!("Unexpected: app is None");
    }
  }
}

#[no_mangle]
pub extern "C" fn test_controller_process_test_controller_thread_notify(channel: microkit_channel) {
  unsafe {
    if let Some(_app) = app.as_mut() {
      _app.notify(channel);
    } else {
      panic!("Unexpected: app is None");
    }
  }
}

