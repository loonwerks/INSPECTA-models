#!/bin/bash -e
# Record what this environment is, so that an installed VM, appliance or
# container can answer the question later.
#
# An OVA is handed around detached from the repository it was built from, and
# months later "which Verus is in this?" is not otherwise answerable without
# starting it and running each tool.  The manifest is written where both a human
# and a script can find it:
#
#   ${PROVERS_DIR}/build-info      the manifest itself; shell-sourceable, with
#                                 quoted values, like /etc/os-release
#   /etc/provers-env-release       the same, for anything expecting os-release
#                                  style discovery (skipped if not writable)
#
# Re-run after updating a tool to refresh it; each per-tool script leaves the
# manifest alone, so it reflects the last time this ran.
set -Eeuo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/env.sh"

: "${PROVERS_BUILD_DATE:=$(date -u +%Y-%m-%dT%H:%M:%SZ)}"

# The revision of the repository these scripts came from, when it is available.
# In a VM the scripts are copied to ~/bin without any .git, and in a container
# they are COPYed, so this is usually empty -- it is recorded when it is not.
_src_rev="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --short HEAD 2>/dev/null || true)"

_ide_list=""
for ide in IVE:PROVERS_IVE CodeIVE:PROVERS_CODEIVE FMIDE:PROVERS_FMIDE; do
  name=${ide%%:*}; var=${ide##*:}
  [ "${!var}" = "true" ] && _ide_list="${_ide_list}${_ide_list:+, }${name}"
done
: "${_ide_list:=none}"

_manifest=$(cat <<EOF
# DARPA PROVERS development environment
# Generated by bin/build-info.sh -- do not edit; re-run to refresh.
PROVERS_BUILD_DATE="${PROVERS_BUILD_DATE}"
PROVERS_BUILD_VER="${PROVERS_BUILD_VER}"
PROVERS_ARCH="${PROVERS_ARCH}"
PROVERS_DIR="${PROVERS_DIR}"
PROVERS_IDES="${_ide_list}"
PROVERS_SCRIPTS_REV="${_src_rev:-unknown}"

SIREUM_V="${SIREUM_V}"
SIREUM_INIT_V="${SIREUM_INIT_V}"
SIREUM_PROFILE="${PROVERS_SIREUM_PROFILE:-full}"
VERUS_VER="${VERUS_VER}"
VERUS_FROM_SOURCE="${VERUS_FROM_SOURCE}"
Z3_VER="${Z3_VER}"
MICROKIT_SDK_VER="${MICROKIT_SDK_VER}"
MICROKIT_DOMAINS_SDK_VER="${MICROKIT_DOMAINS_SDK_VER}"
LIONSOS_VER="${LIONSOS_VER}"
SDFGEN_VER="${SDFGEN_VER}"
SDFGEN_FROM_SOURCE="${SDFGEN_FROM_SOURCE}"
RUST_TOOLCHAIN_VER="${RUST_TOOLCHAIN_VER}"
RUST_NIGHTLY_VER="${RUST_NIGHTLY_VER}"
ZIG_VER="${ZIG_VER}"
ARM_GNU_TOOLCHAIN_VER="${ARM_GNU_TOOLCHAIN_VER}"
EOF
)

mkdir -p "${PROVERS_DIR}"
printf '%s\n' "${_manifest}" > "${PROVERS_DIR}/build-info"

# Best effort: a VM has sudo, a container's final stage may not be root.
if command -v sudo > /dev/null 2>&1; then
  printf '%s\n' "${_manifest}" | sudo tee /etc/provers-env-release > /dev/null 2>&1 || true
fi

echo "Wrote ${PROVERS_DIR}/build-info"
